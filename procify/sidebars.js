// One sidebar per folder inside docs/Docs, built automatically.
// Add a folder with .md files and it gets its own sidebar after the next restart/build.
const fs = require('fs');
const path = require('path');
 
const root = path.join(__dirname, 'docs', 'Docs');
 
const folders = fs.existsSync(root)
  ? fs
      .readdirSync(root, {withFileTypes: true})
      .filter(
        (d) =>
          d.isDirectory() && !d.name.startsWith('.') && !d.name.startsWith('_'),
      )
      .map((d) => d.name)
  : [];
 
const sidebars = {};
 
for (const folder of folders) {
  sidebars[folder] = [
    {
      type: 'category',
      label: folder,
      collapsible: true,
      collapsed: false,
      items: [{type: 'autogenerated', dirName: `Docs/${folder}`}],
    },
  ];
}
 
module.exports = sidebars;